import { defaultParseSearch } from '@tanstack/react-router'
import { describe, expect, test } from 'vitest'

import { communitySsoSearchSchema } from './community-sso-search'

function request(subject?: string, scope = 'chat_session') {
  const query = new URLSearchParams({
    client_id: 'https://studio.example',
    redirect_uri: 'https://studio.example/api/new-api/community/callback',
    response_type: 'code',
    scope,
    state: 'a'.repeat(43),
    code_challenge: 'b'.repeat(43),
    code_challenge_method: 'S256',
  })
  if (subject !== undefined) query.set('expected_subject', subject)
  return defaultParseSearch(`?${query.toString()}`) as Record<string, unknown>
}

describe('community authorization search parameters', () => {
  test('accepts the numeric account ID generated by the studio URL', () => {
    const parsed = request('17')
    expect(parsed.expected_subject).toBe(17)
    expect(communitySsoSearchSchema.parse(parsed).expected_subject).toBe('17')
  })

  test('preserves identity-only authorization without a studio account ID', () => {
    expect(
      communitySsoSearchSchema.parse(request(undefined, 'identity'))
        .expected_subject
    ).toBeUndefined()
  })

  test('accepts an explicitly serialized canonical string account ID', () => {
    expect(communitySsoSearchSchema.parse(request('"17"')).expected_subject).toBe(
      '17'
    )
  })

  test.each(['0', '-1', '1.5', 'true', 'null', '[]', '[17]', '{}', '9007199254740992'])(
    'rejects invalid or imprecise parsed account ID %s',
    (value) => {
      expect(communitySsoSearchSchema.safeParse(request(value)).success).toBe(false)
    }
  )

  test('preserves strict state, challenge, and scope validation', () => {
    for (const bad of [
      { state: 'short' },
      { state: ['a'.repeat(43), 'b'.repeat(43)] },
      { code_challenge: 'short' },
      { code_challenge_method: 'plain' },
      { scope: 'admin' },
    ]) {
      expect(
        communitySsoSearchSchema.safeParse({ ...request('17'), ...bad }).success
      ).toBe(false)
    }
  })
})
